// Ověření hry více hráčů u jednoho počítače: výběr, předání, střídání tahů, zprávy a mlha každého hráče.
import { chromium } from 'playwright'
const url = process.argv[2] || 'http://localhost:5199'
const dir = process.argv[3] || '/tmp/civ-mp'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto(url)
await page.waitForFunction(() => window.game?.isRunning)
await page.evaluate(() => localStorage.clear()); await page.reload(); await page.waitForFunction(() => window.game?.isRunning)
await page.waitForTimeout(500)
const st = () => page.evaluate(() => { const a = window.app, s = a.state; return { me: a.me, cur: s.cur, turn: s.turn, modal: a.hud.modalKind, title: document.querySelector('#modal h2')?.textContent ?? '', nation: document.querySelector('#topbar .nation')?.textContent ?? '', notes: [...document.querySelectorAll('#notes .note')].map(n => n.textContent), cities: s.cities.map(c => [c.owner, c.name]), explored: s.players.map(p => p.explored.reduce((x, y) => x + y, 0)) } })
const out = {}
await page.click('[data-a="m-new"]')
await page.click('[data-a="m-humans"][data-v="2"]')
await page.screenshot({ path: `${dir}/1-setup.png` })
await page.click('[data-a="m-next"]')
await page.click('[data-a="m-nation"][data-v="thal"]'); await page.click('[data-a="m-start"]')
await page.screenshot({ path: `${dir}/2-pick2.png` })
out.takenDisabled = await page.evaluate(() => document.querySelector('[data-a="m-nation"][data-v="thal"]').disabled)
await page.click('[data-a="m-nation"][data-v="khar"]'); await page.click('[data-a="m-start"]')
await page.waitForTimeout(700)
await page.screenshot({ path: `${dir}/3-handover.png` })
out.handover1 = await st()
await page.keyboard.press('Escape'); out.escKeeps = (await st()).modal
await page.click('[data-a="seat"]'); await page.waitForTimeout(500)
out.brief = await st()
await page.screenshot({ path: `${dir}/4-brief.png` })
await page.click('[data-a="close"]'); await page.waitForTimeout(300)
await page.keyboard.press('b'); await page.waitForTimeout(900); await page.keyboard.press('Escape')
out.p0city = await st()
await page.screenshot({ path: `${dir}/5-p0.png` })
await page.keyboard.press('Shift+Enter'); await page.waitForTimeout(1500)
out.handover2 = await st()
await page.screenshot({ path: `${dir}/6-handover2.png` })
await page.keyboard.press('Enter'); await page.waitForTimeout(700)
out.p1 = await st()
await page.screenshot({ path: `${dir}/7-p1.png` })
await page.keyboard.press('b'); await page.waitForTimeout(900); await page.keyboard.press('Escape')
// Hráč 1 vyhlásí válku hráči 0 a nabídne mír (přes okno diplomacie se národy musí znát).
await page.evaluate(() => { const s = window.app.state; s.players[0].met.push(1); s.players[1].met.push(0) })
await page.click('[data-a="diplo"]'); await page.waitForTimeout(200)
await page.screenshot({ path: `${dir}/8-diplo.png` })
await page.click('[data-a="war"][data-v="0"]'); await page.click('#confirm-yes'); await page.waitForTimeout(200)
await page.click('[data-a="peace"][data-v="0"]'); await page.waitForTimeout(200)
out.diploMsg = await page.evaluate(() => document.querySelector('#modal .body p')?.textContent)
await page.screenshot({ path: `${dir}/9-diplo-war.png` })
await page.keyboard.press('Escape')
await page.keyboard.press('Shift+Enter'); await page.waitForTimeout(3000)
out.handover3 = await st()
await page.keyboard.press('Enter'); await page.waitForTimeout(700)
out.p0turn2 = await st()
await page.screenshot({ path: `${dir}/10-offer.png` })
await page.click('[data-a="offer-yes"]'); await page.waitForTimeout(300)
out.afterPeace = await page.evaluate(() => ({ war: window.app.state.players[0].war, offers: window.app.state.offers.length }))
// Pokračování z uložené hry začíná oponou pro hráče na tahu.
await page.reload(); await page.waitForFunction(() => window.game?.isRunning); await page.waitForTimeout(500)
await page.click('[data-a="m-continue"]'); await page.waitForTimeout(700)
out.continued = await st()
// Hra jednoho hráče dál funguje bez opony.
await page.evaluate(() => localStorage.clear()); await page.reload(); await page.waitForFunction(() => window.game?.isRunning); await page.waitForTimeout(400)
await page.click('[data-a="m-new"]'); await page.click('[data-a="m-next"]'); await page.click('[data-a="m-start"]'); await page.waitForTimeout(600)
out.single = await st()
await page.click('[data-a="close"]'); await page.keyboard.press('b'); await page.waitForTimeout(900); await page.keyboard.press('Escape')
await page.keyboard.press('Shift+Enter'); await page.waitForTimeout(3000)
out.single2 = await st()
out.errors = errors
console.log(JSON.stringify(out, null, 1))
await browser.close()
